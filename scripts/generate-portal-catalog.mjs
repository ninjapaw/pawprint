import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path) => JSON.parse(readFileSync(join(root, path), "utf8"));
const configuration = read("config/portal.json");
const shared = read("config/portal-services.json").services;
const platform = read("config/platform.json");
const idPattern = /^[a-z0-9][a-z0-9-]*$/;
const workflowPattern = /^[a-zA-Z0-9._-]+\.ya?ml$/;
const repositories = new Set();
const workflows = {};
const publicWorkloads = configuration.workloads.map((item) => {
  assert(idPattern.test(item.id));
  assert(/^ninjapaw\/[a-z0-9][a-z0-9-]*$/.test(item.repository));
  assert(workflowPattern.test(item.statusWorkflow));
  assert.equal(new URL(item.siteUrl).protocol, "https:");
  assert(!repositories.has(item.id), `Duplicate workload: ${item.id}`);
  repositories.add(item.id);
  const steps = Object.fromEntries(item.steps.map(({ id, workflow, inputs }) => {
    assert(idPattern.test(id));
    return [id, { workflow, inputs }];
  }));
  for (const [id, step] of Object.entries({ ...steps, ...item.hostedActions })) {
    assert(idPattern.test(id));
    assert(workflowPattern.test(step.workflow));
    for (const [key, value] of Object.entries(step.inputs)) {
      assert(/^[a-zA-Z0-9._-]+$/.test(key));
      assert.equal(typeof value, "string");
      assert(/^[a-zA-Z0-9._-]+$/.test(value));
    }
  }
  workflows[item.id] = {
    repository: item.repository,
    steps: { ...steps, ...item.hostedActions },
  };
  return {
    id: item.id, label: item.label, description: item.description,
    repository: item.repository, siteUrl: item.siteUrl,
    statusWorkflow: item.statusWorkflow, steps: Object.keys(workflows[item.id].steps),
  };
});
for (const service of shared) {
  assert(idPattern.test(service.id) && !repositories.has(service.id));
  repositories.add(service.id);
  assert.equal(new URL(service.guideUrl).origin, "https://github.com");
  if (service.statusWorkflow) assert(workflowPattern.test(service.statusWorkflow));
}
const services = [
  ...shared,
  ...publicWorkloads.map((item) => ({
    ...item, kind: "workload",
    resourceTypes: ["Microsoft.Web/staticSites", "Microsoft.Web/sites", "Microsoft.Compute/virtualMachines"],
    guideUrl: `https://github.com/${item.repository}/actions`,
  })),
].map((service) => service.repository && service.statusWorkflow
  ? { ...service, workflowUrl: `https://github.com/${service.repository}/actions/workflows/${service.statusWorkflow}` }
  : service);
const bindingHints = Object.fromEntries(services.map((service) => [
  service.id,
  Object.fromEntries(Object.entries(platform.environments).map(([environment, state]) => {
    const workload = platform.repositories[service.id]?.environments?.[environment];
    return [environment, {
      subscriptionRef: workload?.subscriptionRef ?? state.subscriptionRef,
      resourceGroups: workload
        ? [workload.resourceGroup, ...(workload.additionalResourceGroups ?? []).map((item) => item.resourceGroup)].filter(Boolean)
        : service.kind === "workload" ? [] : [state.platformResourceGroup],
    }];
  })),
]));
const outputs = {
  "public/portal-public.json": `${JSON.stringify({ workloads: publicWorkloads, services }, null, 2)}\n`,
  "api/src/catalog.generated.ts": `// Generated by scripts/generate-portal-catalog.mjs; edit config/portal*.json instead.\nexport const workloads = ${JSON.stringify(workflows, null, 2)} as const;\n\nexport const services = ${JSON.stringify(services, null, 2)} as const;\n\nexport const bindingHints = ${JSON.stringify(bindingHints, null, 2)} as const;\n`,
  "schema/portal.sources.schema.json": `${JSON.stringify({
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: "PawPrint server-only observation bindings",
    type: "object", additionalProperties: false, required: ["subscriptions", "bindings"],
    properties: {
      subscriptions: {
        type: "object", additionalProperties: false,
        properties: Object.fromEntries(["dev", "prod"].map((key) => [key, { type: "string", format: "uuid" }])),
      },
      bindings: {
        type: "object", additionalProperties: false,
        properties: Object.fromEntries(services.map((service) => [service.id, {
          type: "object", additionalProperties: false,
          properties: Object.fromEntries(["dev", "prod"].map((environment) => [environment, {
            type: "object", additionalProperties: false, required: ["desired", "resourceIds"],
            properties: {
              desired: { enum: ["enabled", "disabled", "not-configured"] },
              resourceIds: { type: "array", maxItems: 4, uniqueItems: true, items: { type: "string", pattern: "^/subscriptions/[a-fA-F0-9-]{36}/resourceGroups/[a-zA-Z0-9._()-]+/providers/[a-zA-Z.]+/[a-zA-Z]+/[a-zA-Z0-9._()-]+$" } },
              ...(service.kind === "easm" ? { budgetResourceId: { type: "string", pattern: "^/subscriptions/[a-fA-F0-9-]{36}/resourceGroups/[a-zA-Z0-9._()-]+/providers/Microsoft[.]Consumption/budgets/[a-zA-Z0-9._()-]+$" } } : {}),
            },
          }])),
        }])),
      },
    },
  }, null, 2)}\n`,
};
for (const [path, content] of Object.entries(outputs)) {
  if (process.argv.includes("--check")) {
    assert.equal(readFileSync(join(root, path), "utf8").replaceAll("\r\n", "\n"), content, `Stale generated catalog: ${path}`);
  } else {
    writeFileSync(join(root, path), content);
  }
}
console.log(`Portal catalog ${process.argv.includes("--check") ? "verified" : "generated"}: ${services.length} fixed services.`);
